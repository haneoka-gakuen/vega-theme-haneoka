export function bundledHaneokaChatSource(path: string): string {
  const normalized = path.replace(/\/ChatLINE\/(?=(?:chatwindow_image|back|lock|Icon|stamp)\.png$)/u, "/");
  const direct = HANEOKA_CHAT_SOURCES[normalized];
  if (typeof direct === "string") return direct;
  if (/^adv_data_.*_chaticon_/iu.test(path)) {
    const icon = HANEOKA_CHAT_SOURCES[`Assets/AddressableResources/Adv/Chat/Icon/${path.replace(/\.png$/iu, "")}.png`];
    if (typeof icon === "string") return icon;
  }
  return "";
}

